def arbol(raiz: Path) -> dict[str, str]:
    """Hash de cada archivo bajo `raiz` (incluido .git): para comprobar que algo no escribió nada."""
    return {p.relative_to(raiz).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(raiz.rglob("*")) if p.is_file()}


def correr(vieja, capsys, aplicar=False, procesos=lambda: []) -> tuple[int, str]:
    from ratifact import upgrade
    codigo = upgrade.main(aplicar=aplicar, procesos=procesos, log_viejo=vieja["log"])
    return codigo, capsys.readouterr().out


def test_plan_por_defecto_no_cambia_nada(vieja, entorno, capsys):
    antes = arbol(entorno["tmp"])
    codigo, salida = correr(vieja, capsys)
    assert codigo == 0 and "Dry run: nothing was changed" in salida
    for esperado in ("1. migrate uno", "1. migrate juego", f"2. move uno: {vieja['base'] / '.memorias' / 'uno'} → "
                     f"{vieja['base'] / '.ratifact' / 'uno'}", "2. move dos", "2. keep juego", "3. write",
                     "4. regenerate DECISIONS.md/OPEN.md of dos", "5. copy the usage log"):
        assert esperado in salida, (esperado, salida)
    assert "2. move juego" not in salida
    assert arbol(entorno["tmp"]) == antes


