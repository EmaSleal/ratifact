"""`ratifact upgrade` (T-012, ADR-029): plan sin cambios por defecto; con --apply migra las memorias v1, mueve las de
.memorias/ a .ratifact/ (nunca las rutas propias), escribe ~/.config/ratifact/projects.json con claves en inglés y
renombra el viejo a .bak-v1, regenera las vistas y copia el log viejo. Aborta con servidores en marcha, .lock tomados o
memorias sucias; es idempotente y, si un paso falla, deja todo como estaba antes de ese paso. Todo corre en un HOME
temporal: nunca toca ~/.config ni las memorias reales."""
