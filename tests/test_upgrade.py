def test_fallo_en_el_paso_3_devuelve_las_memorias_y_deja_projects_json(vieja, capsys, monkeypatch):
    from ratifact import upgrade_aplicar
    original = upgrade_aplicar._escribir_config

    def falla(destino, datos):
        destino.parent.mkdir(parents=True, exist_ok=True)
        destino.write_text("{a medias")
        raise OSError("disco lleno (simulado)")
    monkeypatch.setattr(upgrade_aplicar, "_escribir_config", falla)
    base = vieja["base"]
    codigo, salida = correr(vieja, capsys, aplicar=True)
    assert codigo == 1
    assert "step 3 (write projects.json with English keys) failed: OSError: disco lleno (simulado)" in salida
    assert "step 2 (memories moved back)" in salida and "Kept from earlier steps: uno: memory of 'uno' migrated" in salida
    assert (base / ".memorias" / "uno" / "schema.json").exists() and (base / ".memorias" / "dos").is_dir()
    assert not (base / ".ratifact").exists()
    assert vieja["config"].read_bytes() == vieja["original"]
    assert not vieja["nueva"].exists() and not list(vieja["config"].parent.glob("*.bak-v1*"))
    monkeypatch.setattr(upgrade_aplicar, "_escribir_config", original)   # corregida la causa, el apply termina
    assert correr(vieja, capsys, aplicar=True)[0] == 0 and (base / ".ratifact" / "uno").is_dir()


def test_fallo_en_el_paso_1_revierte_las_migraciones_hechas(vieja, capsys, monkeypatch):
    from ratifact import esquema, upgrade_aplicar
    uno = vieja["base"] / ".memorias" / "uno"
    antes = foto(uno)
    original = esquema._migrar

    def migrar(proyecto, mem, actual):
        if proyecto == "juego":
            raise esquema.ErrorMemoria("falla simulada")
        return original(proyecto, mem, actual)
    monkeypatch.setattr(upgrade_aplicar.esquema, "_migrar", migrar)
    codigo, salida = correr(vieja, capsys, aplicar=True)
    assert codigo == 1 and "step 1 (migrate memories to schema v2) failed" in salida
    assert foto(uno) == antes and "pre-v2" not in subprocess.run(["git", "-C", str(uno), "tag"], capture_output=True,
                                                                 text=True).stdout
    assert vieja["config"].read_bytes() == vieja["original"]


def test_despues_del_upgrade_el_servidor_encuentra_todo(vieja, capsys, monkeypatch):
    """Punta a punta: proyectos v1 en .memorias + config vieja → upgrade --apply → get_context y read_task."""
    assert correr(vieja, capsys, aplicar=True)[0] == 0
    capsys.readouterr()
    # el cliente sigue con MEMORIA_PROYECTOS_CONFIG apuntando al archivo renombrado: se usa el nuevo, con aviso
    srv = recargar_servidor()
    from ratifact import config
    assert config.CONFIG == vieja["nueva"] and "was moved to" in capsys.readouterr().err
    for nombre in ("uno", "juego", "dos"):
        assert not srv.get_context(project=nombre).startswith("ERROR")
    assert config._mem("uno") == vieja["base"] / ".ratifact" / "uno"
    tarea = srv.read_task(project="uno", id="T-1")
    assert not tarea.startswith("ERROR") and "T-001" in tarea
    assert "codegraph" not in srv.get_context(project="dos")       # integrations: off se sigue respetando
    monkeypatch.delenv("MEMORIA_PROYECTOS_CONFIG")                  # cliente nuevo: sin variable
    srv = recargar_servidor()
    assert config.CONFIG == vieja["nueva"] and "T-001" in srv.read_task(project="juego", id="T-001")


def _proc_simulado(raiz: Path, pid: int, entorno: dict, cwd: Path | None) -> Path:
    """Un /proc con un `ratifact serve` (cmdline, environ y, si se da, el enlace cwd)."""
    d = raiz / str(pid)
    d.mkdir(parents=True)
    (d / "cmdline").write_bytes(b"/home/u/.local/bin/ratifact\0serve\0")
    (d / "environ").write_bytes(b"".join(f"{k}={v}".encode() + b"\0" for k, v in entorno.items()))
    if cwd is not None:
        (d / "cwd").symlink_to(cwd)
    return raiz


def test_variable_relativa_se_resuelve_contra_el_cwd_del_proceso(vieja, entorno, tmp_path, capsys):
    """Criterio 14: MEMORIA_PROYECTOS_CONFIG=projects.json en un servidor cuyo cwd es la carpeta de esa configuración
    es la misma configuración → bloquea; la misma variable con otro cwd es otra configuración → se ignora."""
    from ratifact.instalacion import procesos_servidor
    env = {"HOME": str(vieja["home"]), "MEMORIA_PROYECTOS_CONFIG": "projects.json"}
    proc = _proc_simulado(tmp_path / "proc", 500, env, vieja["config"].parent)
    antes = arbol(entorno["tmp"])
    codigo, salida = correr(vieja, capsys, aplicar=True, procesos=lambda: procesos_servidor(proc))
    assert codigo == 1 and "server running: pid 500 (/home/u/.local/bin/ratifact serve)" in salida
    assert arbol(entorno["tmp"]) == antes
    otro = _proc_simulado(tmp_path / "proc2", 501, env, tmp_path / "proc2")
    codigo, salida = correr(vieja, capsys, procesos=lambda: procesos_servidor(otro))
    assert codigo == 0 and "Ignored: 1 server process using another configuration" in salida


def test_variable_relativa_sin_cwd_legible_bloquea(vieja, entorno, tmp_path, capsys):
    from ratifact.instalacion import procesos_servidor
