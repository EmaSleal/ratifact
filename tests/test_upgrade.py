def test_apply_migra_mueve_reescribe_y_copia(vieja, capsys):
    base = vieja["base"]
    codigo, salida = correr(vieja, capsys, aplicar=True)
    assert codigo == 0, salida
    assert not (base / ".memorias" / "uno").exists() and not (base / ".memorias" / "dos").exists()
    uno, dos, juego = base / ".ratifact" / "uno", base / ".ratifact" / "dos", base / "juego" / ".project"
    for mem in (uno, juego):          # v1 migradas, con tag de respaldo; la ruta propia no se movió
        assert json.loads((mem / "schema.json").read_text())["version"] == 2 and (mem / "tasks").is_dir()
        assert subprocess.run(["git", "-C", str(mem), "tag"], capture_output=True, text=True).stdout.split() == ["pre-v2"]
    assert "_View generated by ratifact." in (dos / "DECISIONS.md").read_text()
    assert log_git(dos)[0] == "memoria: regenerate views (ratifact upgrade)"
    nueva = json.loads(vieja["nueva"].read_text())
    assert nueva["dos"]["integrations"] == {"codegraph": "off"} and "integraciones" not in nueva["dos"]
    assert {k for p in nueva.values() for k in p} == {"path", "memory", "writable", "tests", "integrations"}
    assert [nueva[n]["memory"] for n in ("dos", "uno", "juego")] == [str(dos), str(uno), str(juego)]
    assert not vieja["config"].exists()
    assert (vieja["config"].with_name("projects.json.bak-v1")).read_bytes() == vieja["original"]
    assert (vieja["home"] / ".local" / "state" / "ratifact" / "uso.jsonl").read_text() == vieja["log"].read_text()
    assert vieja["log"].exists() and "Done:" in salida
    assert "Restart the clients" in salida and "verify with `ratifact doctor`" in salida      # T-016 (ADR-037 §6)


